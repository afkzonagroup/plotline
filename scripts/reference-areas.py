"""Writes test-vectors/areas.json: reference areas of test polygons from
GeographicLib (C. F. F. Karney, "Algorithms for geodesics", J. Geodesy 87,
43-55, 2013), the exact area of a polygon with geodesic sides on the WGS 84
ellipsoid. Plotline's own method (authalic sphere, great-circle sides) is
checked against these values by the TypeScript and Python tests.

Development only. Run with GeographicLib installed:
    python3 -m venv .venv && .venv/bin/pip install geographiclib==2.1
    .venv/bin/python scripts/reference-areas.py
"""
import json
import pathlib
import sys

from geographiclib.geodesic import Geodesic

ROOT = pathlib.Path(__file__).resolve().parent.parent


def square(lon, lat, d):
    return [[lon, lat], [lon + d, lat], [lon + d, lat + d], [lon, lat + d], [lon, lat]]


CASES = [
    ("1 m square at the equator", square(10, 0, 0.00001)),
    ("0.001 degree square at the equator", square(10, 0, 0.001)),
    ("0.001 degree square at 45 N", square(10, 45, 0.001)),
    ("0.001 degree square at 60 S", square(-60, -60, 0.001)),
    ("0.001 degree square at 80 S", square(100, -80, 0.001)),
    ("0.02 degree square (about 4.9 km2) at 6 N", square(-5, 6, 0.02)),
    ("1 degree square at the equator", square(0, 0, 1)),
    ("10 degree square at 30 N", square(20, 30, 10)),
    ("L-shaped concave plot", [[-49.0, -22.7], [-48.99, -22.7], [-48.99, -22.695], [-48.995, -22.695], [-48.995, -22.69], [-49.0, -22.69], [-49.0, -22.7]]),
    ("thin strip 1 km by 10 m", [[30.0, 0.5], [30.009, 0.5], [30.009, 0.50009], [30.0, 0.50009], [30.0, 0.5]]),
    ("near the north pole", square(15, 89.9, 0.05)),
    ("across the antimeridian (unwrapped longitudes)", [[179.99, -17.8], [180.01, -17.8], [180.01, -17.79], [179.99, -17.79], [179.99, -17.8]]),
    ("clockwise ring", list(reversed(square(102, 0.5, 0.01)))),
    ("Commission example: FAZENDA TABOAO II", None),
    ("Commission example: Cocoa Farm 01", None),
]


def official(name):
    # The Commission's examples, copied from the EUDR GeoJSON File Description.
    data = json.loads((ROOT / "test-vectors" / "official-examples.json").read_text("utf-8"))
    for example in data["examples"]:
        for f in json.loads(example["text"])["features"]:
            if f["properties"]["ProductionPlace"] == name:
                return f["geometry"]["coordinates"][0]
    raise SystemExit("example not found: " + name)


def area(ring):
    poly = Geodesic.WGS84.Polygon()
    for lon, lat in ring[:-1]:
        poly.AddPoint(lat, lon)
    _, _, a = poly.Compute(False, True)
    return abs(a)


def main():
    out = []
    for name, ring in CASES:
        if ring is None:
            ring = official(name.split(": ", 1)[1])
        out.append({"name": name, "ring": ring, "squareMetres": round(area(ring), 6)})
    doc = {
        "about": "Reference areas from GeographicLib 2.1 (Karney), exact geodesic polygons on WGS 84. Generated by scripts/reference-areas.py.",
        "cases": out,
    }
    (ROOT / "test-vectors" / "areas.json").write_text(json.dumps(doc, indent=1) + "\n", "utf-8")
    print("wrote", len(out), "cases", file=sys.stderr)


main()

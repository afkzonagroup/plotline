// Writes test-vectors/cases.json (expected results for the shared
// TypeScript/Python test vectors) from the built TypeScript package, and
// python/src/plotline/rules.json (the rule catalogue the Python package
// reads). Run after `npm run build`, and review every changed expectation:
//   node scripts/generate-vectors.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { RULES, fix, validate } from '../dist/index.js';
import { tsOptions } from './generate-vectors-options.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const brief = (issues) => issues.map((i) => ({ rule: i.rule, severity: i.severity, path: i.path, feature: i.feature }));

/** Expected results of one case. */
export function expected(c) {
  const options = { ...tsOptions(c.options), format: c.format };
  const report = validate(c.input, options);
  const fixed = fix(c.input, options);
  return {
    issues: brief(report.issues),
    hectares: report.plots.map((p) => p.hectares),
    output: fixed.output,
    changes: fixed.changes.map((x) => ({ rule: x.rule, path: x.path, feature: x.feature })),
    after: fixed.after === null ? null : brief(fixed.after.issues),
  };
}

const input = JSON.parse(await readFile(join(ROOT, 'test-vectors/cases-input.json'), 'utf8'));
const cases = input.cases.map((c) => ({ name: c.name, expected: expected(c) }));
await writeFile(join(ROOT, 'test-vectors/cases.json'), `${JSON.stringify({ about: 'Expected results for test-vectors/cases-input.json, generated by scripts/generate-vectors.mjs and reviewed by hand. Both implementations must reproduce them exactly (areas to 1e-9 relative).', cases }, null, 1)}\n`);
await writeFile(join(ROOT, 'python/src/plotline/rules.json'), `${JSON.stringify({ about: 'Generated from src/core/rules.ts by scripts/generate-vectors.mjs.', rules: RULES }, null, 1)}\n`);
process.stdout.write(`wrote ${cases.length} cases\n`);
